def test_rms_annulus_requires_target_radius(synthetic_fits):
    """method='annulus' without target_radius_arcsec must raise."""
    with pytest.raises(ValueError, match="target_radius"):
        compute_rms(synthetic_fits, method="annulus")


def test_rms_unknown_method_raises(synthetic_fits):
    with pytest.raises(ValueError, match="Unknown RMS method"):
        compute_rms(synthetic_fits, method="some_fancy_method")


# ---------------------------------------------------------------------------
# compute_rms - justification dict contents
# ---------------------------------------------------------------------------
def test_rms_justification_records_method_parameters(synthetic_fits):
    info = compute_rms(synthetic_fits, method="sigma_clip_excl",
                       exclude_factor=4.0, sigma=3.0, maxiters=5)
    just = info["justification"]
    assert just["method"] == "sigma_clip_excl"
    assert just["sigma"] == 3.0
    assert just["maxiters"] == 5
    assert just["exclude_factor_beam"] == 4.0
    assert "description" in just


# ---------------------------------------------------------------------------
# compute_image_stats - integration of load + RMS + peak
# ---------------------------------------------------------------------------
def test_image_stats_returns_complete_dict(synthetic_fits):
    stats = compute_image_stats(synthetic_fits, rms_method="sigma_clip_excl")
    assert "peak_jy_beam" in stats
    assert "rms_jy_beam" in stats
    assert "snr" in stats
    assert "dynamic_range" in stats
    assert "bmaj_arcsec" in stats
    assert "bmin_arcsec" in stats


def test_image_stats_dynamic_range_is_sensible(synthetic_fits):
    """For a 5 mJy/bm source over 10 uJy/bm noise, DR should be ~500."""
    stats = compute_image_stats(synthetic_fits, rms_method="sigma_clip_excl")
    dr = stats["dynamic_range"]
    assert 300 < dr < 700


def test_image_stats_snr_equals_dr(synthetic_fits):
    """In the current implementation snr and dynamic_range are identical
    (peak / off-source RMS)."""
    stats = compute_image_stats(synthetic_fits, rms_method="sigma_clip_excl")
    assert stats["snr"] == pytest.approx(stats["dynamic_range"], rel=1e-9)


def test_image_stats_handles_noise_only(synthetic_fits_no_source):
    """A pure-noise image should give a low (~1-5) DR, not crash."""
    stats = compute_image_stats(synthetic_fits_no_source, rms_method="sigma_clip_excl")
    assert math.isfinite(stats["dynamic_range"])
    assert stats["dynamic_range"] < 20  # mostly random; certainly not 100+
